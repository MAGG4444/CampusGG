require('reflect-metadata');
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { DataSource } = require('typeorm');
const { User } = require('../dist/users/user.entity');
const { ForumPost } = require('../dist/forum/forum-post.entity');
const { ForumPostLike } = require('../dist/forum/forum-post-like.entity');
const { ForumComment } = require('../dist/forum/forum-comment.entity');
const { ForumCommentLike } = require('../dist/forum/forum-comment-like.entity');
const { ForumCommentsService } = require('../dist/forum/forum-comments.service');
const { AddForumCommentThreads1792368010000 } = require('../dist/database/migrations/add-forum-comment-threads');
const { AddForumCommentTombstones1792368012000 } = require('../dist/database/migrations/add-forum-comment-tombstones');

test('comment threads preserve parents, isolate posts, and enforce likes and ownership', async t => {
  assert.ok(process.env.DATABASE_URL, 'DATABASE_URL is required');
  const schema = `test_comment_${randomUUID().replaceAll('-', '')}`;
  const db = new DataSource({ type: 'postgres', url: process.env.DATABASE_URL, schema, entities: [User, ForumPost, ForumPostLike, ForumComment, ForumCommentLike] });
  await db.initialize();
  t.after(async () => { await db.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`); await db.destroy(); });
  await db.query(`CREATE SCHEMA "${schema}"`);
  await db.synchronize();
  await db.query(`DROP TABLE "${schema}"."forum_comment_likes"`);
  await db.query(`ALTER TABLE "${schema}"."forum_comments" DROP COLUMN "parent_reply_id"`);
  await db.query(`ALTER TABLE "${schema}"."forum_comments" DROP COLUMN "deleted_at"`);
  await db.query(`ALTER TABLE "${schema}"."forum_comments" ALTER COLUMN "author_id" SET NOT NULL`);
  const runner = db.createQueryRunner();
  await new AddForumCommentThreads1792368010000().up(runner);
  await new AddForumCommentTombstones1792368012000().up(runner);
  await runner.release();
  const users = db.getRepository(User), posts = db.getRepository(ForumPost), comments = db.getRepository(ForumComment), likes = db.getRepository(ForumCommentLike);
  const a = await users.save({ email: 'a@example.edu', username: 'usera', displayName: 'Player A', eduVerified: true });
  const b = await users.save({ email: 'b@example.edu', username: 'userb', displayName: 'Player B', eduVerified: true });
  const p = await posts.save({ title: 'Test post', content: 'Text', author: a });
  const other = await posts.save({ title: 'Other post', content: 'Text', author: a });
  const service = new ForumCommentsService(comments, posts, users, likes);
  const root = await service.create(p.id, { content: 'Main' }, a.id);
  const child = await service.create(p.id, { content: 'Child', parentReplyId: root.id }, b.id);
  const grandchild = await service.create(p.id, { content: 'Grandchild', parentReplyId: child.id }, a.id);
  assert.equal(grandchild.parentReplyId, child.id);
  await assert.rejects(service.create(other.id, { content: 'Wrong post', parentReplyId: root.id }, b.id));
  await assert.rejects(service.setLike(p.id, child.id, a.id, true));
  assert.equal((await service.setLike(p.id, root.id, b.id, true)).likeCount, 1);
  assert.equal((await service.setLike(p.id, root.id, b.id, true)).likeCount, 1);
  assert.deepEqual((await service.likedIds(p.id, b.id)).ids, [root.id]);
  assert.deepEqual((await service.likedIds(p.id, a.id)).ids, []);
  const listed = await service.findAll(p.id, 1, 50);
  assert.equal(listed.comments.find(c => c.id === root.id).likeCount, 1);
  assert.equal(listed.comments.find(c => c.id === child.id).parentReplyId, root.id);
  await assert.rejects(service.update(p.id, root.id, { content: 'No' }, b.id));
  await assert.rejects(service.remove(p.id, root.id, b.id));
  assert.equal((await service.remove(p.id, root.id, a.id)).tombstone, true);
  let after = await service.findAll(p.id, 1, 50);
  const tombstone = after.comments.find(c => c.id === root.id);
  assert.equal(tombstone.content, '');
  assert.equal(tombstone.author, null);
  assert.ok(tombstone.deletedAt);
  assert.equal(after.comments.find(c => c.id === child.id).parentReplyId, root.id);
  assert.equal(after.comments.find(c => c.id === grandchild.id).parentReplyId, child.id);
  assert.equal((await comments.findOneBy({id:root.id})).content, '');
  assert.deepEqual((await service.likedIds(p.id, b.id)).ids, []);
  await assert.rejects(service.setLike(p.id, root.id, b.id, true));
  await assert.rejects(service.update(p.id, root.id, {content:'restore'}, a.id));
  await assert.rejects(service.create(p.id, {content:'new', parentReplyId:root.id}, a.id));
  assert.equal((await service.remove(p.id, child.id, b.id)).tombstone, true);
  after = await service.findAll(p.id, 1, 50);
  assert.equal(after.comments.find(c => c.id === child.id).author, null);
  assert.equal(after.comments.find(c => c.id === grandchild.id).parentReplyId, child.id);
  assert.equal((await service.remove(p.id, grandchild.id, a.id)).tombstone, false);
  assert.equal(await comments.countBy({id:grandchild.id}), 0);
  assert.equal(await comments.countBy({id:child.id}), 0);
  assert.equal(await comments.countBy({id:root.id}), 0);
});
