require('reflect-metadata');
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { DataSource } = require('typeorm');
const { Test } = require('@nestjs/testing');
const { getRepositoryToken } = require('@nestjs/typeorm');
const { JwtModule, JwtService } = require('@nestjs/jwt');
const { ValidationPipe } = require('@nestjs/common');
const load = (path, name) => require(`../dist/${path}`)[name];
const User = load('users/user.entity', 'User');
const Post = load('forum/forum-post.entity', 'ForumPost');
const Like = load('forum/forum-post-like.entity', 'ForumPostLike');
const Comment = load('forum/forum-comment.entity', 'ForumComment');
const Channel = load('forum/forum-channel.entity', 'ForumChannel');
const Follow = load('forum/forum-channel-follow.entity', 'ForumChannelFollow');
const PostFollow = load('forum/forum-post-follow.entity', 'ForumPostFollow');
const PostFollowMigration = load('database/migrations/add-forum-post-follows', 'AddForumPostFollows1792368009000');
const FollowMigration = load('database/migrations/add-forum-channel-follows', 'AddForumChannelFollows1792368007000');
const Migration = load('database/migrations/add-forum-channels', 'AddForumChannels1792368006000');
const RankIndexes = load('database/migrations/add-forum-ranking-indexes', 'AddForumRankingIndexes1792368008000');

test('persistent channels filter historical posts and paginate deterministically', async t => {
  assert.ok(process.env.DATABASE_URL, 'DATABASE_URL is required');
  const schema = `test_channels_${randomUUID().replaceAll('-', '')}`;
  const entities = [User, Post, Like, Comment, Channel, Follow, PostFollow];
  const db = new DataSource({ type: 'postgres', url: process.env.DATABASE_URL, schema, entities, synchronize: false });
  await db.initialize();
  let app;
  t.after(async () => { if (app) await app.close(); await db.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`); await db.destroy(); });
  await db.query(`CREATE SCHEMA "${schema}"`);
  await db.synchronize();
  await db.query(`DROP TABLE "${schema}"."forum_post_follows"`);
  // Exercise the migration against a schema with existing posts and no channel table.
  await db.query(`DROP TABLE "${schema}"."forum_channel_follows"`);
  await db.query(`DROP TABLE "${schema}"."forum_channels"`);
  const user = await db.getRepository(User).save({ email: 'channels@example.edu', username: 'channeluser', displayName: 'Player', eduVerified: true, password: 'hash' });
  const saved = await db.getRepository(Post).save(['CS2', ' Counter-Strike 2 ', null, 'Unknown game'].map((game, i) => ({ author: user, title: `Post ${i}`, content: 'Content', game, createdAt: new Date('2026-01-01T00:00:00Z') })));
  const runner = db.createQueryRunner();
  await new PostFollowMigration().up(runner);
  await new PostFollowMigration().up(runner);
  const migration = new Migration();
  await migration.up(runner);
  const firstCatalog = await db.getRepository(Channel).find({ order: { id: 'ASC' } });
  await migration.up(runner);
  assert.deepEqual(await db.getRepository(Channel).find({ order: { id: 'ASC' } }), firstCatalog);
  assert.deepEqual((await db.getRepository(Post).find({ order: { title: 'ASC' } })).map(post => post.game), ['CS2', ' Counter-Strike 2 ', null, 'Unknown game']);
  assert.equal(new Set(firstCatalog.map(channel => channel.slug)).size, firstCatalog.length);
  const aliases = firstCatalog.flatMap(channel => channel.aliases);
  assert.equal(new Set(aliases).size, aliases.length);
  await assert.rejects(migration.down(), /cannot be reverted safely/);
  await new FollowMigration().up(runner);
  await new RankIndexes().up(runner);
  await new RankIndexes().up(runner);
  // Development schema synchronization must not remove migration-owned indexes.
  await db.synchronize();
  const indexes = await db.query("SELECT indexname FROM pg_indexes WHERE schemaname = $1 AND indexname IN ('IDX_forum_comments_post', 'IDX_forum_posts_rank_date')", [schema]);
  assert.deepEqual(indexes.map(row => row.indexname).sort(), ['IDX_forum_comments_post', 'IDX_forum_posts_rank_date']);
  await runner.release();
  const module = await Test.createTestingModule({
    imports: [JwtModule.register({ secret: 'integration-test-secret' })],
    controllers: [load('forum/forum.controller', 'ForumController'), load('forum/forum-channels.controller', 'ForumChannelsController'), load('forum/forum-follows.controller', 'ForumFollowsController'), load('forum/forum-ranking.controller', 'ForumRankingController'), load('forum/forum-post-follows.controller', 'ForumPostFollowsController')],
    providers: [load('forum/forum.service', 'ForumService'), load('forum/forum-channels.service', 'ForumChannelsService'), load('forum/forum-follows.service', 'ForumFollowsService'), load('forum/forum-ranking.service', 'ForumRankingService'), load('forum/forum-post-follows.service', 'ForumPostFollowsService'), ...entities.map(entity => ({ provide: getRepositoryToken(entity), useValue: db.getRepository(entity) }))],
  }).compile();
  app = module.createNestApplication({ logger: false });
  app.useGlobalPipes(new ValidationPipe({ whitelist: true, transform: true }));
  await app.listen(0, '127.0.0.1');
  await db.getRepository(Comment).save({ post: saved[0], author: user, content: 'Reply' });
  const get = async path => { const r = await fetch((await app.getUrl()) + path); return { status: r.status, body: await r.json() }; };
  const allSearch = await get('/forum/feed/all?search=post%200&sort=new&limit=1');
  assert.equal(allSearch.status, 200);
  assert.equal(allSearch.body.total, 1);
  assert.equal(allSearch.body.posts[0].id, saved[0].id);
  assert.equal(allSearch.body.posts[0].replyCount, 1);
  assert.equal(allSearch.body.posts[0].likeCount, 0);
  assert.equal((await get('/forum/feed/all?search=nonexistent')).body.total, 0);
  assert.equal((await get('/forum/feed/all?sort=replies')).body.posts[0].id, saved[0].id);
  assert.equal((await get('/forum/feed/all?sort=invalid')).status, 400);
  const filtered = await get('/forum/feed/all?channel=counter-strike-2&sort=new');
  assert.equal(filtered.status, 200);
  assert.equal(filtered.body.total, 2);
  assert.equal((await get('/forum/feed/all?channel=missing')).status, 404);
  const channels = await get('/forum/channels');
  assert.equal(channels.status, 200);
  assert.equal(channels.body.find(channel => channel.slug === 'counter-strike-2').category, 'FPS');
  assert.equal(channels.body.find(channel => channel.slug === 'minecraft').category, 'Sandbox');
  assert.ok(channels.body.every(channel => channel.followerCount === 0));
  assert.equal((await get('/forum/channels/COUNTER-STRIKE-2')).body.name, 'CS2');
  assert.equal((await get('/forum/channels/not-a-game')).status, 404);
  assert.equal((await get('/forum/channels/not-a-game/posts')).status, 404);
  const first = (await get('/forum/channels/counter-strike-2/posts?limit=1&page=1')).body;
  const second = (await get('/forum/channels/counter-strike-2/posts?limit=1&page=2')).body;
  assert.equal(first.total, 2); assert.equal(second.total, 2);
  assert.equal(first.limit, 1); assert.equal(second.page, 2);
  assert.notEqual(first.posts[0].id, second.posts[0].id);
  assert.ok(first.posts[0].id > second.posts[0].id);
  assert.equal([...first.posts, ...second.posts].find(post => post.id === saved[0].id).replyCount, 1);
  const home = (await get('/forum/posts')).body;
  assert.equal(home.total, 4);
  assert.ok(home.posts.some(post => post.id === saved[2].id && post.game === null));
  assert.ok(home.posts.some(post => post.id === saved[3].id));
  const token = module.get(JwtService).sign({ sub: user.id });
  const create = async (body, authenticated = true) => {
    const response = await fetch((await app.getUrl()) + '/forum/posts', { method: 'POST', headers: { 'Content-Type': 'application/json', ...(authenticated ? { Authorization: `Bearer ${token}` } : {}) }, body: JSON.stringify(body) });
    return { status: response.status, body: await response.json() };
  };
  const input = { title: 'New channel post', content: 'Hello' };
  assert.equal((await create({ ...input, channelSlug: 'valorant' }, false)).status, 401);
  assert.equal((await create(input)).status, 400);
  assert.equal((await create({ ...input, channelSlug: 'missing' })).status, 400);
  assert.equal((await create({ ...input, game: 'unknown game' })).status, 400);
  assert.equal((await create({ ...input, channelSlug: 'valorant', game: 'CS2' })).status, 400);
  const created = await create({ ...input, channelSlug: 'valorant' });
  assert.equal(created.status, 201); assert.equal(created.body.game, 'Valorant');
  assert.ok((await get('/forum/channels/valorant/posts')).body.posts.some(post => post.id === created.body.id));
  const legacy = await create({ ...input, game: ' Counter-Strike 2 ' });
  assert.equal(legacy.status, 201); assert.equal(legacy.body.game, 'CS2');
  const user2 = await db.getRepository(User).save({ email: 'other@example.edu', username: 'otherplayer', displayName: 'Other', eduVerified: true, password: 'hash' });
  const token2 = module.get(JwtService).sign({ sub: user2.id });
  const call = async (path, method = 'GET', auth = token) => {
    const response = await fetch((await app.getUrl()) + path, { method, headers: auth ? { Authorization: `Bearer ${auth}` } : {} });
    return { status: response.status, body: await response.json() };
  };
  assert.equal((await call(`/forum/posts/${saved[0].id}/follow`, 'POST', null)).status, 401);
  assert.equal((await call(`/forum/post-follows?ids=${saved[0].id}`, 'GET', null)).status, 401);
  assert.equal((await call(`/forum/post-follows?ids=${saved[0].id}`, 'GET', 'invalid-token')).status, 401);
  assert.equal((await call('/forum/channels/counter-strike-2/following/posts', 'GET', null)).status, 401);
  assert.equal((await call('/forum/posts/not-a-uuid/follow', 'POST')).status, 400);
  assert.equal((await call(`/forum/posts/${randomUUID()}/follow`, 'POST')).status, 404);
  const postFollowResults = await Promise.all(Array.from({ length: 4 }, () => call(`/forum/posts/${saved[0].id}/follow`, 'POST')));
  assert.ok(postFollowResults.every(result => result.status === 201 && result.body.following));
  assert.equal(await db.getRepository(PostFollow).countBy({ userId: user.id, postId: saved[0].id }), 1);
  await call(`/forum/posts/${saved[1].id}/follow`, 'POST');
  await call(`/forum/posts/${created.body.id}/follow`, 'POST', token2);
  assert.deepEqual((await call(`/forum/post-follows?ids=${saved[0].id},${saved[1].id}`)).body.followedIds.sort(), [saved[0].id, saved[1].id].sort());
  assert.equal((await call('/forum/channels/counter-strike-2/following/posts', 'GET', token2)).body.total, 0);
  const followed1 = (await call('/forum/channels/counter-strike-2/following/posts?sort=new&limit=1&page=1')).body;
  const followed2 = (await call('/forum/channels/counter-strike-2/following/posts?sort=new&limit=1&page=2')).body;
  assert.equal(followed1.total, 2); assert.notEqual(followed1.posts[0].id, followed2.posts[0].id);
  assert.equal((await call('/forum/channels/counter-strike-2/following/posts?search=Post%200')).body.total, 1);
  await call(`/forum/posts/${saved[0].id}/follow`, 'POST', token2);
  const rankedChannel = (await get('/forum/channels/counter-strike-2/posts?sort=followed&limit=100')).body;
  assert.equal(rankedChannel.posts[0].id, saved[0].id);
  assert.equal(rankedChannel.posts[1].id, saved[1].id);
  assert.ok(rankedChannel.posts.some(post => post.id === legacy.body.id));
  const rankedGlobal = (await get('/forum/feed/all?sort=followed&limit=1&page=1')).body;
  assert.equal(rankedGlobal.posts[0].id, saved[0].id);
  const rankPage1 = (await call('/forum/channels/counter-strike-2/following/posts?sort=followed&limit=1&page=1')).body;
  const rankPage2 = (await call('/forum/channels/counter-strike-2/following/posts?sort=followed&limit=1&page=2')).body;
  assert.equal(rankPage1.posts[0].id, saved[0].id); assert.equal(rankPage2.posts[0].id, saved[1].id);
  assert.equal((await call('/forum/channels/valorant/following/posts?sort=followed', 'GET', token2)).body.total, 1);
  await call(`/forum/posts/${saved[0].id}/follow`, 'DELETE', token2);
  const tied = (await call('/forum/channels/counter-strike-2/following/posts?sort=followed')).body.posts;
  assert.ok(tied[0].id > tied[1].id);
  assert.equal((await get('/forum/channels/counter-strike-2/posts?search=Post%200&limit=1')).body.total, 1);
  assert.equal((await call(`/forum/posts/${saved[0].id}/follow`, 'DELETE')).body.following, false);
  assert.equal((await call('/forum/channels/counter-strike-2/following/posts')).body.total, 1);
  assert.equal((await call('/forum/channels/valorant/follow', 'POST', null)).status, 401);
  assert.equal((await call('/forum/channels/missing/follow', 'POST')).status, 404);
  const simultaneous = await Promise.all(Array.from({ length: 4 }, () => call('/forum/channels/counter-strike-2/follow', 'POST')));
  assert.ok(simultaneous.every(result => result.status === 201 && result.body.following));
  assert.equal(await db.getRepository(Follow).countBy({ userId: user.id }), 1);
  assert.equal((await call('/forum/channels/counter-strike-2/follow')).body.following, true);
  assert.equal((await call('/forum/me/channels', 'GET', token2)).body.length, 0);
  assert.equal((await call('/forum/channels/valorant/follow', 'POST')).body.following, true);
  assert.equal((await get('/forum/channels')).body.find(channel => channel.slug === 'valorant').followerCount, 1);
  assert.equal((await call('/forum/channels/valorant/follow', 'POST', token2)).body.following, true);
  assert.equal((await get('/forum/channels')).body.find(channel => channel.slug === 'valorant').followerCount, 2);
  assert.equal((await call('/forum/channels/valorant/follow', 'DELETE', token2)).body.following, false);
  const feed = (await call('/forum/me/following/posts?limit=100')).body;
  assert.equal(feed.total, 4);
  assert.ok(feed.posts.some(post => post.id === saved[0].id));
  assert.ok(feed.posts.some(post => post.id === saved[1].id));
  assert.ok(feed.posts.every(post => post.game && post.game !== 'Unknown game'));
  const page1 = (await call('/forum/me/following/posts?page=1&limit=1')).body;
  const page2 = (await call('/forum/me/following/posts?page=2&limit=1')).body;
  assert.equal(page1.total, 4); assert.notEqual(page1.posts[0].id, page2.posts[0].id);
  assert.equal((await call('/forum/me/following/posts', 'GET', token2)).body.total, 0);
  assert.equal((await call('/forum/channels/valorant/follow', 'DELETE')).body.following, false);
  assert.equal((await get('/forum/channels')).body.find(channel => channel.slug === 'valorant').followerCount, 0);
  assert.equal((await call('/forum/channels/valorant/follow', 'DELETE')).body.following, false);
  assert.equal((await call('/forum/me/channels')).body.length, 1);
  assert.equal((await call('/forum/channels/missing/follow', 'DELETE')).status, 404);
  assert.equal((await call('/forum/feed/for-you', 'GET', null)).status, 401);
  assert.equal((await call('/forum/feed/popular?sort=invalid')).status, 400);
  assert.equal((await call('/forum/feed/popular?sort=top&window=invalid')).status, 400);
  assert.equal((await call('/forum/feed/popular?limit=101')).status, 400);
  const popular = await call('/forum/feed/popular?sort=new&limit=100');
  assert.equal(popular.status, 200);
  assert.ok(popular.body.posts.every(post => post.game && post.game !== 'Unknown game'));
  for (const sort of ['new', 'hot', 'top']) {
    const result = await call(`/forum/feed/popular?sort=${sort}&window=all`);
    assert.equal(result.status, 200);
    assert.equal((await call(`/forum/channels/counter-strike-2/posts?sort=${sort}`)).status, 200);
  }
  for (const window of ['today', 'week', 'month', 'all']) assert.equal((await call(`/forum/feed/popular?sort=top&window=${window}`)).status, 200);
  const personal = await call('/forum/feed/for-you?limit=100');
  assert.equal(personal.status, 200);
  assert.ok(personal.body.posts.some(post => post.id === created.body.id));
  assert.ok(personal.body.posts.some(post => post.id === saved[2].id));
  assert.equal((await call('/forum/feed/for-you', 'GET', token2)).status, 200);
  const p1 = (await call('/forum/feed/for-you?limit=1&page=1')).body;
  const p2 = (await call('/forum/feed/for-you?limit=1&page=2')).body;
  assert.notEqual(p1.posts[0].id, p2.posts[0].id);
  const now = Date.now();
  const sameTime = new Date(now - 60000);
  const [csNew, valorantNew, oldPopular] = await db.getRepository(Post).save([
    { author: user, title: 'CS recent', content: 'text', game: 'CS2', createdAt: sameTime },
    { author: user, title: 'Valorant recent', content: 'text', game: 'Valorant', createdAt: sameTime },
    { author: user, title: 'Old popular', content: 'text', game: 'CS2', createdAt: new Date(now - 45 * 86400000) },
  ]);
  await db.getRepository(Comment).save(Array.from({ length: 6 }, (_, index) => ({ post: oldPopular, author: user, content: `reply ${index}` })));
  const byId = (list, id) => list.findIndex(post => post.id === id);
  const aliceRank = (await call('/forum/feed/for-you?limit=100')).body.posts;
  assert.ok(byId(aliceRank, csNew.id) < byId(aliceRank, valorantNew.id));
  assert.ok(byId(aliceRank, valorantNew.id) >= 0);
  assert.equal((await call('/forum/channels/valorant/follow', 'POST', token2)).status, 201);
  const bobRank = (await call('/forum/feed/for-you?limit=100', 'GET', token2)).body.posts;
  assert.ok(byId(bobRank, valorantNew.id) < byId(bobRank, csNew.id));
  const hot = (await call('/forum/feed/popular?sort=hot&limit=100')).body.posts;
  const top = (await call('/forum/feed/popular?sort=top&window=all&limit=100')).body.posts;
  assert.ok(byId(hot, csNew.id) < byId(hot, oldPopular.id));
  assert.ok(byId(top, oldPopular.id) < byId(top, csNew.id));
  const recentTop = (await call('/forum/feed/popular?sort=top&window=month&limit=100')).body.posts;
  assert.equal(byId(recentTop, oldPopular.id), -1);
  const channelTop = (await call('/forum/channels/counter-strike-2/posts?sort=top&limit=100')).body.posts;
  assert.ok(byId(channelTop, oldPopular.id) >= 0);
  assert.equal(byId(channelTop, valorantNew.id), -1);
  const mutation = await create({ title: 'Refresh integration post', content: 'Initial content', channelSlug: 'valorant' });
  assert.equal(mutation.status, 201);
  assert.ok((await get('/forum/feed/all?search=Refresh%20integration')).body.posts.some(post => post.id === mutation.body.id));
  const edit = await fetch((await app.getUrl()) + `/forum/posts/${mutation.body.id}`, { method: 'PATCH', headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ title: 'Updated refresh title' }) });
  assert.equal(edit.status, 200);
  assert.ok((await get('/forum/channels/valorant/posts?search=Updated%20refresh')).body.posts.some(post => post.id === mutation.body.id));
  assert.equal((await call(`/forum/posts/${mutation.body.id}`, 'DELETE')).status, 200);
  assert.equal((await get('/forum/feed/all?search=Updated%20refresh')).body.total, 0);
});
