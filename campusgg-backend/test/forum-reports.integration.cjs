require('reflect-metadata');
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { DataSource } = require('typeorm');
const { Test } = require('@nestjs/testing');
const { getRepositoryToken } = require('@nestjs/typeorm');
const { JwtModule, JwtService } = require('@nestjs/jwt');
const { ValidationPipe } = require('@nestjs/common');
const { User } = require('../dist/users/user.entity');
const { ForumPost } = require('../dist/forum/forum-post.entity');
const { ForumPostLike } = require('../dist/forum/forum-post-like.entity');
const { ForumComment } = require('../dist/forum/forum-comment.entity');
const { ForumReport } = require('../dist/forum/forum-report.entity');
const { ForumReportsController } = require('../dist/forum/forum-reports.controller');
const { AddForumReports1792368011000 } = require('../dist/database/migrations/add-forum-reports');

test('reports validate authentication and persist selected reason and details', async t => {
  assert.ok(process.env.DATABASE_URL, 'DATABASE_URL is required');
  const schema = `test_reports_${randomUUID().replaceAll('-', '')}`;
  const entities = [User, ForumPost, ForumPostLike, ForumComment, ForumReport];
  const db = new DataSource({type:'postgres',url:process.env.DATABASE_URL,schema,entities});
  await db.initialize(); let app;
  t.after(async () => { if (app) await app.close(); await db.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`); await db.destroy(); });
  await db.query(`CREATE SCHEMA "${schema}"`); await db.synchronize();
  await db.query(`DROP TABLE "${schema}"."forum_reports"`);
  const runner = db.createQueryRunner(); await new AddForumReports1792368011000().up(runner); await runner.release();
  const user = await db.getRepository(User).save({email:'reporter@example.edu',username:'reporter',eduVerified:true});
  const post = await db.getRepository(ForumPost).save({title:'Test post',content:'text',author:user});
  const other = await db.getRepository(ForumPost).save({title:'Other post',content:'text',author:user});
  const comment = await db.getRepository(ForumComment).save({content:'reply',post,author:user});
  const module = await Test.createTestingModule({imports:[JwtModule.register({secret:'test-secret'})],controllers:[ForumReportsController],providers:entities.map(entity => ({provide:getRepositoryToken(entity),useValue:db.getRepository(entity)}))}).compile();
  app = module.createNestApplication({logger:false}); app.useGlobalPipes(new ValidationPipe({whitelist:true,transform:true})); await app.listen(0,'127.0.0.1');
  const jwt = module.get(JwtService).sign({sub:user.id});
  const url = await app.getUrl();
  const send = (path, body, token=jwt) => fetch(`${url}${path}`, {method:'POST',headers:{'Content-Type':'application/json',...(token?{Authorization:`Bearer ${token}`}:{})},body:JSON.stringify(body)});
  assert.equal((await send(`/forum/posts/${post.id}/report`,{reason:'spam'},null)).status,401);
  assert.equal((await send(`/forum/posts/${post.id}/report`,{reason:'other'})).status,400);
  assert.equal((await send(`/forum/posts/${post.id}/report`,{reason:'invalid'})).status,400);
  assert.equal((await send(`/forum/posts/${other.id}/comments/${comment.id}/report`,{reason:'spam'})).status,404);
  assert.equal((await send(`/forum/posts/${post.id}/comments/${comment.id}/report`,{reason:'other',customReason:'Custom',details:'Details'})).status,201);
  const [report] = await db.getRepository(ForumReport).find({relations:{comment:true,reporter:true}});
  assert.equal(report.comment.id,comment.id); assert.equal(report.reporter.id,user.id); assert.equal(report.customReason,'Custom'); assert.equal(report.details,'Details');
});
